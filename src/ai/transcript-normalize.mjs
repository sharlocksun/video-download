function subtitleLanguageArgs(preference = 'zh-first') {
  const key = String(preference || 'zh-first');
  if (key === 'en-first') return 'en.*,en,zh.*,zh';
  if (key === 'zh-only') return 'zh.*,zh,zh-Hans,zh-Hant,en.*,en';
  if (key === 'en-only') return 'en.*,en';
  if (key === 'all') return 'all';
  return 'zh.*,zh,zh-Hans,zh-Hant,en.*,en';
}

function normalizeTranscriptText(text = '', options = {}) {
  const script = String(options.transcriptScript || 'simplified');
  if (script === 'simplified' || script === 'bilingual') return toSimplifiedChinese(text);
  return String(text || '');
}

export {
  normalizeTranscriptText,
  subtitleLanguageArgs,
  toSimplifiedChinese,
};
